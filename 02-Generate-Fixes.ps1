# Template 2: patch
# =================================================================================================
$tplPatch = @'
<#
 Generated by 02-Generate-Fixes.ps1 for @@HOST@@ on @@DATE@@
 PATCH PHP at @@PHPDIR@@ from @@VERSION@@ to @@TARGET@@.

 Before running:
   1. Download this file on a machine with internet and copy it to the server:
        @@ZIPNAME@@
      Expected location (verify the exact name on the site): https://windows.php.net/downloads/releases/@@ZIPNAME@@
   2. Put it at: @@ZIPPATH@@   (or pass -PhpZip <path>)
   3. Run 1-interim.ps1 first if the site cannot wait, and take a backup of the whole @@PHPDIR@@ parent folder and the databases.
 @@UPGRADENOTE@@
 The script checks that the new build matches the old one (compiler, 32/64-bit, thread-safe) so it loads into this Apache.
 If anything fails it puts the old PHP back automatically.
#>
[CmdletBinding()]
param(
    [string]$PhpZip = '@@ZIPPATH@@',
    [switch]$ConfirmBranchUpgrade
)
$PhpDir      = '@@PHPDIR@@'
$ApacheRoot  = '@@APACHE@@'
$TargetVer   = '@@TARGET@@'
$BranchUpgrade = [bool]@@BRANCHUPGRADE@@
$OldCompiler = '@@COMPILER@@'
$OldArch     = '@@ARCH@@'
$OldTS       = '@@TS@@'
@@COMMON@@

if ($BranchUpgrade -and -not $ConfirmBranchUpgrade) {
    throw 'This moves PHP to a newer branch (@@VERSION@@ -> @@TARGET@@). Test the sites on a copy first, then re-run with -ConfirmBranchUpgrade.'
}
if (-not (Test-Path $PhpZip)) { throw "PHP zip not found: $PhpZip" }
if (-not (Test-Path $PhpDir)) { throw "PHP folder not found: $PhpDir" }

$newDir  = "${PhpDir}_new_$stamp"
$oldDir  = "${PhpDir}_old_$stamp"
$confBak = if ($ApacheRoot) { Join-Path $ApacheRoot "conf_bak_$stamp" } else { $null }

Write-Host "Extracting $PhpZip ..."
Expand-Archive -Path $PhpZip -DestinationPath $newDir -Force
$newExe = Join-Path $newDir 'php.exe'
if (-not (Test-Path $newExe)) { Remove-Item $newDir -Recurse -Force; throw 'php.exe not found in the zip.' }

$ni = @(Invoke-Native { & $newExe -i })
function Pick([string]$n) { $m = $ni | Where-Object { $_ -like "$n =>*" } | Select-Object -First 1; if ($m) { ($m -replace '^[^=]*=>\s*', '').Trim() } }
$newVer = Pick 'PHP Version'; $newComp = Pick 'Compiler'; $newArch = Pick 'Architecture'; $newTS = Pick 'Thread Safety'
Write-Host "New build: PHP $newVer / $newComp / $newArch / thread-safe=$newTS"
if (-not $newVer) { Remove-Item $newDir -Recurse -Force; throw 'The new php.exe cannot run here (is the Visual C++ runtime installed?).' }
$problems = @()
if ([version]($newVer -replace '[^\d\.].*$', '') -lt [version]$TargetVer) { $problems += "zip contains PHP $newVer, expected $TargetVer or newer" }
if ($newArch -ne $OldArch) { $problems += "architecture differs (old $OldArch, new $newArch)" }
if ($newTS -ne $OldTS)     { $problems += "thread safety differs (old $OldTS, new $newTS) - mod_php needs the thread-safe (Win32) build" }
if ($newComp -ne $OldCompiler) { $problems += "compiler differs (old '$OldCompiler', new '$newComp') - Apache must be built with the same Visual C++ version as PHP" }
if ($problems.Count) { Remove-Item $newDir -Recurse -Force; throw ("Zip does not match this server:`n - " + ($problems -join "`n - ")) }

function Rollback {
    Write-Warning 'Rolling back to the previous PHP...'
    try { Stop-ApacheSafe } catch {}
    if (Test-Path $newDir) { Remove-Item -Path $newDir -Recurse -Force -ErrorAction SilentlyContinue }
    if (Test-Path $oldDir) {
        if (Test-Path $PhpDir) { Rename-Item -Path $PhpDir -NewName ((Split-Path $PhpDir -Leaf) + "_failed_$stamp") }
        Rename-Item -Path $oldDir -NewName (Split-Path $PhpDir -Leaf)
    }
    if ($confBak -and (Test-Path $confBak)) { Copy-Item -Path (Join-Path $confBak '*') -Destination (Join-Path $ApacheRoot 'conf') -Recurse -Force }
    try { Start-ApacheSafe } catch {}
    Write-Warning 'Previous PHP restored. Investigate before retrying.'
}

try {
    if ($ApacheRoot) { Copy-Item -Path (Join-Path $ApacheRoot 'conf') -Destination $confBak -Recurse; Write-Host "Backed up Apache conf to $confBak" }

    # carry over php.ini, extra folders (logs, tmp, sessions ...) and - same branch only - extension DLLs that the zip lacks
    Get-ChildItem -Path $PhpDir -Force | Where-Object { -not (Test-Path (Join-Path $newDir $_.Name)) } | Where-Object { $_.PSIsContainer -or $_.Extension -notin '.dll', '.exe' } |
        ForEach-Object { Copy-Item -Path $_.FullName -Destination $newDir -Recurse -Force; Write-Host "  carried over $($_.Name)" }
    $iniOld = Join-Path $PhpDir 'php.ini'
    if (Test-Path $iniOld) { Copy-Item -Path $iniOld -Destination (Join-Path $newDir 'php.ini') -Force; Write-Host '  carried over php.ini (your settings, including any interim ones)' }
    if (-not $BranchUpgrade -and (Test-Path (Join-Path $PhpDir 'ext'))) {
        Get-ChildItem -Path (Join-Path $PhpDir 'ext') -Filter '*.dll' | Where-Object { -not (Test-Path (Join-Path $newDir "ext\$($_.Name)")) } |
            ForEach-Object { Copy-Item $_.FullName (Join-Path $newDir 'ext') ; Write-Warning "  copied third-party extension $($_.Name) from old PHP - check it is compatible" }
    }
    elseif ($BranchUpgrade) { Write-Warning 'Branch upgrade: third-party extensions and removed php.ini directives must be reviewed by hand (run php -m and read any startup warnings).' }

    Write-Host 'Stopping Apache...'
    Stop-ApacheSafe
    Rename-Item -Path $PhpDir -NewName (Split-Path $oldDir -Leaf)
    Rename-Item -Path $newDir -NewName (Split-Path $PhpDir -Leaf)

    # make Apache point at the right DLL names (matters when moving from PHP 7 to 8)
    if ($ApacheRoot) {
        $newDll = Get-ChildItem -Path $PhpDir -Filter 'php*apache2*.dll' | Select-Object -First 1
        $newTs  = Get-ChildItem -Path $PhpDir -Filter 'php*ts.dll' | Select-Object -First 1
        if (-not $newTs) { throw 'No php*ts.dll in the new PHP - this is not the thread-safe build.' }
        if (-not $newDll) { throw 'No php*apache2*.dll in the new PHP - this is not the thread-safe build.' }
        Get-ChildItem -Path (Join-Path $ApacheRoot 'conf') -Recurse -Filter '*.conf' | ForEach-Object {
            $t = Get-Content -Path $_.FullName -Raw
            $n = $t -replace '(?i)php\d?apache2_4\.dll', $newDll.Name -replace '(?i)php\d?ts\.dll', $newTs.Name -replace '(?i)LoadModule\s+php7_module', 'LoadModule php_module'
            if ($n -ne $t) { Set-Content -Path $_.FullName -Value $n -Encoding ASCII -NoNewline; Write-Host "  updated PHP module names in $($_.FullName)" }
        }
        if (-not (Test-ApacheConfig)) { throw 'httpd -t failed with the new PHP.' }
    }

    Write-Host 'Checking the new PHP starts cleanly...'
    $warn = @(Invoke-Native { & (Join-Path $PhpDir 'php.exe') -m } | Where-Object { $_ -match '(?i)warning|error|unable|fatal' })
    if ($warn.Count) { $warn | ForEach-Object { Write-Warning "  php -m: $_" }; throw 'PHP printed startup warnings (usually a missing extension or removed php.ini directive).' }
    & (Join-Path $PhpDir 'php.exe') -v

    Start-ApacheSafe
    if ($ApacheRoot -and -not (Get-Process -Name httpd -ErrorAction SilentlyContinue | Where-Object { $_.Path -like "$ApacheRoot*" })) { throw 'Apache did not start with the new PHP.' }
    Show-LoadedPhp
}
catch {
    Write-Warning $_.Exception.Message
    Rollback
    exit 1
}
Write-Host ''
Write-Host "DONE. PHP is now $TargetVer or newer. The old PHP is kept at $oldDir (delete after the sites are tested)."
Write-Host 'Next: browse and test every site on this server, then run 03-Validate.ps1.'
'@

# =================================================================================================
# Template 3: manual rollback
# =================================================================================================
$tplRollback = @'
<#
 Generated by 02-Generate-Fixes.ps1 for @@HOST@@ on @@DATE@@
 Manual ROLLBACK: puts back the newest PHP folder that 2-patch.ps1 renamed to <php>_old_<time>,
 and the newest Apache conf backup (conf_bak_<time>).
#>
$PhpDir     = '@@PHPDIR@@'
$ApacheRoot = '@@APACHE@@'
@@COMMON@@
$old = Get-ChildItem -Path (Split-Path $PhpDir -Parent) -Directory | Where-Object { $_.Name -like ((Split-Path $PhpDir -Leaf) + '_old_*') } | Sort-Object Name -Descending | Select-Object -First 1
if (-not $old) { throw 'No <php>_old_* folder found - nothing to roll back to.' }
$bak = if ($ApacheRoot) { Get-ChildItem -Path $ApacheRoot -Directory | Where-Object { $_.Name -like 'conf_bak_*' } | Sort-Object Name -Descending | Select-Object -First 1 }
Write-Host "Rolling back to $($old.FullName)"
Stop-ApacheSafe
Rename-Item -Path $PhpDir -NewName ((Split-Path $PhpDir -Leaf) + "_rolledback_$stamp")
Rename-Item -Path $old.FullName -NewName (Split-Path $PhpDir -Leaf)
if ($bak) { Copy-Item -Path (Join-Path $bak.FullName '*') -Destination (Join-Path $ApacheRoot 'conf') -Recurse -Force; Write-Host "Restored Apache conf from $($bak.FullName)" }
Start-ApacheSafe
Show-LoadedPhp
Write-Host 'Rolled back. This server is vulnerable again - fix it properly as soon as the cause is found.'
'@

# =================================================================================================
# Generate
# =================================================================================================
$hostName = $r.Host
$date = Get-Date -Format 'yyyy-MM-dd HH:mm'
$plan = New-Object System.Collections.Generic.List[string]
$plan.Add("PHP2Shell fix plan for $hostName   (generated $date from $(Split-Path $ResultFile -Leaf))")
$plan.Add(('=' * 72))
$n = 0
$todo = @($r.Installs | Where-Object { -not $_.IsBackupCopy -and $_.Status -ne 'FIXED' })
if ($todo.Count -eq 0) { $plan.Add('No vulnerable live PHP installs in the result file. Run 03-Validate.ps1 to confirm.') }

foreach ($i in $todo) {
    $n++
    $apache = @($r.Apache | Where-Object { $_.Root -and ((Split-Path $_.Root -Parent) -ieq (Split-Path $i.PhpDir -Parent)) }) | Select-Object -First 1
    $apacheRoot = if ($apache) { $apache.Root } else { '' }
    $branch = [string]$i.Branch
    $vs = ''
    if ($i.Compiler -match '2019') { $vs = 'vs16' } elseif ($i.Compiler -match '2022') { $vs = 'vs17' } elseif ($i.Compiler -match '2017') { $vs = 'vs15' }
    if (-not $vs) { if ($branch -in '8.2', '8.3') { $vs = 'vs16' } elseif ($branch -in '8.4', '8.5') { $vs = 'vs17' } }
    $branchUpgrade = $false
    $manual = ''
    if ($FixedVersions.ContainsKey($branch)) { $target = $FixedVersions[$branch] }
    elseif ($vs -eq 'vs16') { $target = $FixedVersions['8.3']; $branchUpgrade = $true }
    else { $target = ''; $manual = "PHP $($i.Version) was built with '$($i.Compiler)'. The fixed builds that match it do not exist for this branch. This server needs a manual move to a supported PHP and an Apache built for the same Visual C++ version (or a rebuilt server)." }
    $ts   = if ($i.ThreadSafety -eq 'enabled') { 'Win32' } else { 'nts-Win32' }
    $arch = if ($i.Architecture -match '64') { 'x64' } else { 'x86' }
    $zipName = if ($target) { "php-$target-$ts-$vs-$arch.zip" } else { '' }
    $zipPath = Join-Path $DownloadDir $zipName
    $prefix  = '{0}_{1}' -f $hostName, $n

    $plan.Add('')
    $plan.Add("[$n] PHP at $($i.PhpDir)   version $($i.Version)   status $($i.Status)")
    $plan.Add("    Apache      : $(if ($apacheRoot) { $apacheRoot } else { 'not found next to PHP - stop/start Apache yourself' })")
    $plan.Add("    Loaded ini  : $($i.LoadedIni)")
    if ($manual) { $plan.Add("    MANUAL      : $manual"); $plan.Add('    Until then : run the interim script and consider restricting or taking the site offline (CISA advice for PHP 8.1 and older).') }
    else {
        $plan.Add("    Target      : PHP $target$(if ($branchUpgrade) { '  (BRANCH UPGRADE - test the sites first)' })")
        $plan.Add("    Download    : $zipName   -> https://windows.php.net/downloads/releases/$zipName   (verify exact file name on the site)")
        $plan.Add("    Copy it to  : $zipPath")
    }

    $reps = @{
        '@@HOST@@' = $hostName; '@@DATE@@' = $date; '@@PHPDIR@@' = (Q $i.PhpDir); '@@PHPINI@@' = (Q $i.LoadedIni)
        '@@APACHE@@' = (Q $apacheRoot); '@@VERSION@@' = $i.Version; '@@BRANCH@@' = $branch; '@@TARGET@@' = $target
        '@@ZIPNAME@@' = $zipName; '@@ZIPPATH@@' = (Q $zipPath); '@@BRANCHUPGRADE@@' = $(if ($branchUpgrade) { '$true' } else { '$false' })
        '@@COMPILER@@' = (Q $i.Compiler); '@@ARCH@@' = (Q $i.Architecture); '@@TS@@' = (Q $i.ThreadSafety)
        '@@UPGRADENOTE@@' = $(if ($branchUpgrade) { 'NOTE: this is a BRANCH UPGRADE. Check WordPress, themes and plugins support the new PHP on a staging copy first.' } else { 'Same-branch security update: low risk to applications.' })
    }
    function Expand([string]$tpl) {
        $t = $tpl.Replace('@@COMMON@@', $common)
        foreach ($k in $reps.Keys) { $t = $t.Replace($k, [string]$reps[$k]) }
        return $t
    }
    if ($i.LoadedIni) {
        $f1 = Join-Path $OutDir "${prefix}_1-interim.ps1"
        Set-Content -Path $f1 -Value (Expand $tplInterim) -Encoding UTF8
        $plan.Add("    Run 1st     : $f1   (minutes, reversible)")
    } else { $plan.Add('    No php.ini is loaded - interim script skipped; create php.ini from php.ini-production first.') }
    if ($target) {
        $f2 = Join-Path $OutDir "${prefix}_2-patch.ps1"
        $f3 = Join-Path $OutDir "${prefix}_3-rollback.ps1"
        Set-Content -Path $f2 -Value (Expand $tplPatch) -Encoding UTF8
        Set-Content -Path $f3 -Value (Expand $tplRollback) -Encoding UTF8
        $plan.Add("    Run 2nd     : $f2$(if ($branchUpgrade) { ' -ConfirmBranchUpgrade' })")
        $plan.Add("    If it breaks: $f3  (the patch script also rolls back by itself on errors)")
    }
}
$plan.Add('')
$plan.Add('After patching run 03-Validate.ps1 on this server. It must report FIXED before you close the ticket.')
$planFile = Join-Path $OutDir "${hostName}_fix-plan.txt"
Set-Content -Path $planFile -Value $plan -Encoding UTF8
$plan | ForEach-Object { Write-Host $_ }
Write-Host ''
Write-Host "Plan written to $planFile"
