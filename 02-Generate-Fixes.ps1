<#
.SYNOPSIS
  STEP 2 - Read the JSON from step 1 and GENERATE per-server fix scripts. Nothing is changed by this script.

.DESCRIPTION
  For every live (non-backup) PHP install that is not fixed, writes into -OutDir:
     <HOST>_<n>_1-interim.ps1   quick protection: php.ini settings + Apache request-size cap (reversible, backs up first)
     <HOST>_<n>_2-patch.ps1     swaps the PHP folder for the fixed build you downloaded (backs up, tests, rolls back on failure)
     <HOST>_<n>_3-rollback.ps1  puts the previous PHP folder and Apache config back
     <HOST>_fix-plan.txt        what to run, in which order, which zip to download
  Review each generated script, then run them yourself in an elevated PowerShell. Order: 1-interim, then 2-patch.

.PARAMETER ResultFile  The <HOST>_detect_*.json file written by step 1.
.PARAMETER OutDir      Where generated scripts go. Default C:\PHP2Shell\fix
.PARAMETER DownloadDir Folder where you put the PHP zip on the server. Default C:\PHP2Shell\downloads

.EXAMPLE
  .\02-Generate-Fixes.ps1 -ResultFile C:\PHP2Shell\results\WEB01_detect_20261022_160000.json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ResultFile,
    [string]$OutDir = 'C:\PHP2Shell\fix',
    [string]$DownloadDir = 'C:\PHP2Shell\downloads'
)

$ErrorActionPreference = 'Stop'
$null = New-Item -ItemType Directory -Force -Path $OutDir
$r = Get-Content -Raw -Path $ResultFile | ConvertFrom-Json
$FixedVersions = @{ '8.5' = '8.5.12'; '8.4' = '8.4.27'; '8.3' = '8.3.36'; '8.2' = '8.2.35' }
function Q([string]$s) { return ($s -replace "'", "''") }

# =================================================================================================
# Shared helper block pasted into every generated script
# =================================================================================================
$common = @'
$ErrorActionPreference = 'Stop'
$stamp = Get-Date -Format 'yyyyMMdd_HHmmss'
function Invoke-Native([scriptblock]$Block) {
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    try { & $Block 2>&1 | ForEach-Object { "$_" } } finally { $ErrorActionPreference = $old }
}
function Test-Admin { ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator) }
if (-not (Test-Admin)) { throw 'Run this script in an elevated (administrator) PowerShell.' }

function Get-ApacheService {
    if (-not $ApacheRoot) { return $null }
    Get-CimInstance Win32_Service | Where-Object { $_.PathName -match 'httpd' -and $_.PathName -match [regex]::Escape($ApacheRoot) } | Select-Object -First 1
}
function Stop-ApacheSafe {
    if (-not $ApacheRoot) { Write-Warning 'No Apache root known - stop Apache yourself.'; return }
    $svc = Get-ApacheService
    if ($svc) { Write-Host "Stopping service $($svc.Name)"; Stop-Service -Name $svc.Name -Force; (Get-Service $svc.Name).WaitForStatus('Stopped', [TimeSpan]::FromSeconds(60)) }
    Get-Process -Name httpd -ErrorAction SilentlyContinue | Where-Object { $_.Path -like "$ApacheRoot*" } | Stop-Process -Force
    Start-Sleep -Seconds 2
}
function Start-ApacheSafe {
    if (-not $ApacheRoot) { Write-Warning 'No Apache root known - start Apache yourself.'; return }
    $svc = Get-ApacheService
    if ($svc) { Write-Host "Starting service $($svc.Name)"; Start-Service -Name $svc.Name }
    else { Write-Host 'No Windows service found - starting httpd.exe directly. If you normally use the XAMPP Control Panel, stop this copy there and start Apache from the panel.'
           Start-Process -FilePath (Join-Path $ApacheRoot 'bin\httpd.exe') -WindowStyle Hidden }
    Start-Sleep -Seconds 4
}
function Test-ApacheConfig {
    if (-not $ApacheRoot) { return $true }
    $out = @(Invoke-Native { & (Join-Path $ApacheRoot 'bin\httpd.exe') -t })
    $out | ForEach-Object { Write-Host "  httpd -t: $_" }
    return [bool]($out -match 'Syntax OK')
}
function Show-LoadedPhp {
    Start-Sleep -Seconds 2
    $any = $false
    foreach ($p in (Get-Process -Name httpd -ErrorAction SilentlyContinue)) {
        foreach ($m in ($p.Modules | Where-Object { $_.ModuleName -match '^php\d*ts\.dll$' })) {
            Write-Host ("  Apache pid {0} has loaded {1} version {2}" -f $p.Id, $m.FileName, $m.FileVersionInfo.ProductVersion); $any = $true }
    }
    if (-not $any) { Write-Warning 'No PHP DLL seen in a running httpd process (Apache stopped, or PHP runs through FastCGI).' }
}
'@

