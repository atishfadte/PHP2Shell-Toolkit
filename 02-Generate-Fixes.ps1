# Template 1: interim protection
# =================================================================================================
$tplInterim = @'
<#
 Generated by 02-Generate-Fixes.ps1 for @@HOST@@ on @@DATE@@
 INTERIM protection for PHP2Shell on PHP at @@PHPDIR@@ (version @@VERSION@@).
 This only closes the attack paths PHP has confirmed. It does NOT replace patching (2-patch.ps1).
 -LimitRequestBody caps request size in Apache (default 32 MB). Raise it if the sites accept bigger uploads.
 Set -SkipApache to change only php.ini.
#>
[CmdletBinding()]
param([int64]$LimitRequestBody = 33554432, [switch]$SkipApache)
$PhpIni     = '@@PHPINI@@'
$ApacheRoot = '@@APACHE@@'
$Branch     = '@@BRANCH@@'
@@COMMON@@

function ConvertTo-Bytes([string]$v) {
    if ($v -match '^\s*(-?\d+)\s*([KkMmGg]?)') {
        $n = [int64]$Matches[1]
        switch ($Matches[2].ToUpper()) { 'K' { return $n * 1KB } 'M' { return $n * 1MB } 'G' { return $n * 1GB } default { return $n } }
    }
    return 0
}
function Set-Ini([string]$Name, [string]$Value, [switch]$OnlyLower) {
    $lines = @(Get-Content -Path $PhpIni)
    $idx = -1
    for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -match ('^\s*' + [regex]::Escape($Name) + '\s*=')) { $idx = $i } }
    if ($idx -ge 0 -and $OnlyLower) {
        $cur = ($lines[$idx] -split '=', 2)[1].Trim()
        $cb = ConvertTo-Bytes $cur
        if ($cb -gt 0 -and $cb -le (ConvertTo-Bytes $Value)) { Write-Host "  keep  $Name = $cur (already at or below $Value)"; return }
    }
    if ($idx -ge 0) { $lines[$idx] = "$Name = $Value" } else { $lines += "$Name = $Value" }
    Set-Content -Path $PhpIni -Value $lines -Encoding ASCII
    Write-Host "  set   $Name = $Value"
}

if (-not (Test-Path $PhpIni)) { throw "php.ini not found at $PhpIni" }
$iniBackup = "$PhpIni.bak_$stamp"
Copy-Item -Path $PhpIni -Destination $iniBackup
Write-Host "Backed up php.ini to $iniBackup"

Write-Host 'Applying PHP settings...'
Set-Ini 'session.upload_progress.enabled' '0'
if ($Branch -eq '8.5') { Set-Ini 'fatal_error_backtraces' '0' }
Set-Ini 'post_max_size' '32M' -OnlyLower
Set-Ini 'upload_max_filesize' '16M' -OnlyLower

$confBackup = $null
if (-not $SkipApache -and $ApacheRoot) {
    $httpdConf = Join-Path $ApacheRoot 'conf\httpd.conf'
    $extra     = Join-Path $ApacheRoot 'conf\extra\php2shell-hardening.conf'
    $confBackup = "$httpdConf.bak_$stamp"
    Copy-Item -Path $httpdConf -Destination $confBackup
    Set-Content -Path $extra -Encoding ASCII -Value @(
        '# Added for PHP2Shell interim protection - remove after PHP is patched and tested',
        "LimitRequestBody $LimitRequestBody")
    if (-not (Select-String -Path $httpdConf -Pattern 'php2shell-hardening\.conf' -Quiet)) {
        Add-Content -Path $httpdConf -Encoding ASCII -Value "`r`nInclude `"conf/extra/php2shell-hardening.conf`""
    }
    Write-Host "Apache: LimitRequestBody $LimitRequestBody (backup of httpd.conf: $confBackup)"
    if (-not (Test-ApacheConfig)) {
        Write-Warning 'Apache config test failed - restoring httpd.conf and php.ini.'
        Copy-Item -Path $confBackup -Destination $httpdConf -Force
        Copy-Item -Path $iniBackup -Destination $PhpIni -Force
        throw 'Aborted: configuration restored from backup.'
    }
}

Write-Host 'Restarting Apache so the settings load...'
Stop-ApacheSafe
Start-ApacheSafe
Show-LoadedPhp
Write-Host ''
Write-Host 'DONE (interim). This server is still vulnerable until PHP itself is patched. Next: 2-patch.ps1'
Write-Host "To undo: copy $iniBackup back over $PhpIni$(if ($confBackup) { " and $confBackup back over $httpdConf" }), then restart Apache."
'@

